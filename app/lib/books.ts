// 책을 고르면, 모든 책에 똑같은 범용 템플릿 한 문장 대신 그 책의 핵심 포인트 2가지를
// 보여준다. guidePoints에 그 유형이 없는 책(구체적 포인트를 뽑기엔 요약이 너무
// 일반적인 책)은 기존 범용 템플릿 문장 하나로 대신한다.
export function bookGuideFor(
  book: RecommendedBook,
  writingType: WritingType
): { intro: string; points: string[] } {
  const points = book.guidePoints?.[writingType];
  if (points) {
    return { intro: GUIDE_INTRO[writingType](book.title), points };
  }
  return { intro: BOOK_PROMPT_TEMPLATES[writingType](book.title), points: [] };
}

// 학년 + 글의 종류에 맞는 책만 골라 돌려준다.
// 그 유형에 어울리는 책이 없으면 빈 배열을 돌려준다 (예: 감상문은 책이 아니라 영화·공연·전시처럼
// 직접 보고 겪은 대상을 다루는 글이라, 추천도서와 연결하지 않는다).
export function booksFor(gradeBand: GradeBand, writingType: WritingType): RecommendedBook[] {
  return RECOMMENDED_BOOKS.filter(
    (b) => b.gradeBands.includes(gradeBand) && b.suitableTypes.includes(writingType)
  );
}

export function booksForGradeAll(gradeBand: GradeBand): RecommendedBook[] {
  return RECOMMENDED_BOOKS.filter((b) => b.gradeBands.includes(gradeBand));
}
